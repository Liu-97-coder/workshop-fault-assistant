def find_case(text):
    """根据问题文本返回命中的案例（dict），没命中返回 None。"""
    for case in CASES:
        if any(kw in text for kw in case["keywords"]):
            return case
    return None


# 否定前缀：这些字紧贴在关键词前面，说明是"否定"，不算命中。
_NEG = {"没", "不", "无", "非", "别"}


def _hit(text, keywords):
    """
    判断 keywords 里是否有某个词在 text 中"肯定"出现。
    - 长词优先，避免"亮"先命中"灯不亮"
    - 关键词前紧挨着否定字（没/不/无…）时跳过，不算命中
    """
    for kw in sorted(keywords, key=len, reverse=True):
        start = 0
        while True:
            idx = text.find(kw, start)
            if idx == -1:
                break
            prev = text[idx - 1] if idx > 0 else ""
            if prev not in _NEG:
                return True
            start = idx + len(kw)
    return False


def triage(case, text):
    """用户没等问就直接说出具体现象词时，命中返回 {'advice':..., 'goto':-1}；否则 None。"""
    for item in case.get("triage", []):
        if _hit(text, item["keywords"]):
            return {"advice": item["advice"], "goto": -1}
    return None
